<?php

use Illuminate\Foundation\Application;
use Illuminate\Http\Request;

define('LARAVEL_START', microtime(true));

// Setup temporary directories for writable paths in Vercel Serverless environment
$tmpDirs = [
    '/tmp/views',
    '/tmp/storage/framework/cache/data',
    '/tmp/storage/framework/sessions',
    '/tmp/storage/framework/views',
    '/tmp/storage/logs',
    '/tmp/bootstrap/cache',
];

foreach ($tmpDirs as $dir) {
    if (!is_dir($dir)) {
        @mkdir($dir, 0755, true);
    }
}

putenv('APP_CONFIG_CACHE=/tmp/bootstrap/cache/config.php');
putenv('APP_EVENTS_CACHE=/tmp/bootstrap/cache/events.php');
putenv('APP_PACKAGES_CACHE=/tmp/bootstrap/cache/packages.php');
putenv('APP_ROUTES_CACHE=/tmp/bootstrap/cache/routes.php');
putenv('APP_SERVICES_CACHE=/tmp/bootstrap/cache/services.php');
putenv('VIEW_COMPILED_PATH=/tmp/views');

// Autoload composer
require __DIR__ . '/../vendor/autoload.php';

// Bootstrap Laravel and handle the request
/** @var Application $app */
$app = require_once __DIR__ . '/../bootstrap/app.php';

// Set writable storage path
$app->useStoragePath('/tmp/storage');

$kernel = $app->make(Illuminate\Contracts\Http\Kernel::class);

$request = Request::capture();

try {
    $response = $kernel->handle($request);
} catch (\Throwable $e) {
    header('Content-Type: text/plain');
    http_response_code(500);
    echo "=== FATAL LARAVEL EXCEPTION ===\n";
    echo get_class($e) . ": " . $e->getMessage() . "\n";
    echo "File: " . $e->getFile() . ":" . $e->getLine() . "\n\n";
    echo $e->getTraceAsString();
    exit;
}

// If 500 response was generated by Laravel error handler, print details if debug
if ($response->getStatusCode() === 500 && request()->has('debug')) {
    header('Content-Type: text/plain');
    echo "=== 500 STATUS CODE GENERATED ===\n";
    $logFile = '/tmp/storage/logs/laravel.log';
    if (file_exists($logFile)) {
        echo "=== LOG CONTENT ===\n";
        echo file_get_contents($logFile);
    }
    exit;
}

$response->send();

$kernel->terminate($request, $response);
